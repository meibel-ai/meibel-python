def _resolve_csv_type(annotation: Any) -> str:
    """Map a Python type annotation to a CSV column type string."""
    # Unwrap Optional
    origin = getattr(annotation, "__origin__", None)
    if origin is typing.Union:
        args = getattr(annotation, "__args__", ())
        non_none = [a for a in args if a is not type(None)]
        if len(non_none) == 1:
            return _resolve_csv_type(non_none[0])

    if annotation in _PYTHON_TO_CSV_TYPE:
        return _PYTHON_TO_CSV_TYPE[annotation]

    return "string"


